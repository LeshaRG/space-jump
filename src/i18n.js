function lang() {
  return DICT[YSDK.lang] ? YSDK.lang : "en";
}

/** t("play") или t("buyFor", 50) для строк-функций. */
export function t(key, ...args) {
  const value = DICT[lang()][key] ?? DICT.en[key] ?? key;
  return typeof value === "function" ? value(...args) : value;
}

const lastLine = {};

/** Случайная реплика группы без повтора предыдущей. */
export function line(group, ...args) {
  const list = LINES[lang()][group] ?? LINES.en[group];
  if (!list || !list.length) return "";
  let i = Math.floor(Math.random() * list.length);
  if (list.length > 1 && i === lastLine[group]) i = (i + 1) % list.length;
  lastLine[group] = i;
  const v = list[i];
  return typeof v === "function" ? v(...args) : v;
}

export default { t, line };
