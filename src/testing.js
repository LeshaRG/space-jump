/**
 * testing.js — что доступно только тестировщикам.
 *
 * Тестовые хосты: этот компьютер (localhost), телефон в той же сети
 * (192.168.*, 10.*, 172.16–31.*, Tailscale 100.64–127.*) и GitHub Pages.
 * На Яндекс Играх игра открывается с домена Яндекса — там тестовых
 * кнопок нет, даже если SDK не загрузился.
 */
export function isTestHost() {
  const h = location.hostname;
  return h === "localhost" || h === "127.0.0.1" || h === "[::1]" || h === "::1"
    || h.endsWith(".github.io")
    || /^(10|192\.168)\./.test(h)
    || /^172\.(1[6-9]|2\d|3[01])\./.test(h)
    || /^100\.(6[4-9]|[7-9]\d|1[01]\d|12[0-7])\./.test(h);
}

export default { isTestHost };
